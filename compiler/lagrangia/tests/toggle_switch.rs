//! Lagrangia reducer integration test on ToggleSwitch.speck.
//!
//! v1.1: real Z3 wiring. The `invariant_distance` term is now computed by
//! shelling out to `z3 -smt2` for each candidate's invariant obligations,
//! not a static proxy. The "gold" candidate should verify as `Proved`
//! (invariants hold), while perturbed candidates that break guards should
//! return `Counterexample`.
//!
//! Implements spec §2.4 (v0 search procedure) on the ToggleSwitch example:
//!   1. Seed: generate N=20 candidate implementations from the spec IR
//!      (random perturbations: rename variables, reorder struct fields,
//!      inline vs extract helper functions).
//!   2. Score: compute S(impl) for each candidate — now with real Z3 distance.
//!   3. Descend: for top 5, generate 5 local perturbations each. Keep any
//!      with lower action. 3 rounds.
//!   4. Select: candidate with lowest action is the stationary point.
//!
//! Falsification condition (spec §2.6 #1): the action functional does not
//! produce a well-defined minimum (scores flat or chaotic) — the "manifold"
//! has no stationary point. This test PASSES if a stationary point is found
//! and the stationary candidate verifies as `Proved` via Z3.

use lagrangia::{action, byte_entropy, complexity, verify_candidate, ImplCandidate, InvariantObligation, Z3Result};
use std::sync::atomic::{AtomicU64, Ordering};

static NEXT_ID: AtomicU64 = AtomicU64::new(0);

fn next_id() -> u64 {
    NEXT_ID.fetch_add(1, Ordering::SeqCst)
}

