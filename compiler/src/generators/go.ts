function stateVarsOf(name: string): string {
  const t = stateVarTypes.get(name);
  if (t && t.type === 'list') return goType(t.elementType, 'Spot', new Map());
  return 'any';
}
// Map { "k" -> v, ... } -> map[K]V{ "k": v, ... } for a map-typed target.
function lowerMapLiteral(val: string, vt: any): string | null {
  const m = val.match(/^Map\s*\{([\s\S]*)\}$/);
  if (!m || vt?.type !== 'map') return null;
  const keyT = goType(vt.keyType, '', currentEnumMap);
  const valT = goType(vt.valueType, '', currentEnumMap);
  // split pairs at top-level commas
  const pairs: string[] = [];
  let d = 0, inStr = false, start = 0;
  const inner = m[1];
  for (let i = 0; i < inner.length; i++) {
    const ch = inner[i];
    if (ch === '"') inStr = !inStr;
    if (inStr) continue;
    if (ch === '(' || ch === '[' || ch === '{') d++;
    else if (ch === ')' || ch === ']' || ch === '}') d--;
    else if (ch === ',' && d === 0) { pairs.push(inner.slice(start, i)); start = i + 1; }
  }
  pairs.push(inner.slice(start));
  const entries = pairs.map(p => {
    const am = p.split('->');
    if (am.length !== 2) return null;
    return `${am[0].trim()}: ${am[1].trim()}`;
  }).filter(Boolean);
  return `map[${keyT}]${valT}{ ${entries.join(', ')} }`;
}

function fixRecordLiteral(expr: string, elemType: string): string {
  // uppercase record literal fields: CardEvent { cardId: x } -> CardEvent{ CardId: x }
  const m = expr.match(/^(\w+)\s*\{([\s\S]*)\}$/);
  if (!m) return expr;
  const inner = m[2].replace(/(\w+)\s*:/g, (_, f) => `${goName(f)}:`);
  return `${m[1]}{ ${inner} }`;
}

function emitSpeck(speck: SpeckNode): string {
  stateVarTypes = new Map();
  for (const m of speck.members) {
    if (m.type === 'state') for (const v of (m as any).variables) stateVarTypes.set((v as any).name, v.typeExpr);
  }
  const deduped = new Map<string, MemberNode>();
  for (const m of speck.members) {
    const key = memberKey(m);
    const existing = deduped.get(key);
    if (!existing || isEmptyStub(existing)) deduped.set(key, m);
  }
  const members = Array.from(deduped.values());

  // Merge all state members (multiple entities per speck)
  const stateNodes = members.filter(m => m.type === 'state') as StateNode[];
  let mergedState: any = undefined;
  if (stateNodes.length > 0) {
    mergedState = { type: 'state', variables: stateNodes.flatMap(function(n) { return n.variables; }) } as any;
  }
  const stateNode: any = mergedState;
  const initNodes = members.filter(m => m.type === 'init') as any[];  const initNode: any = initNodes.length > 0 ? {
    type: 'init',
    assignments: initNodes.flatMap(function(n) { return n.assignments; }),
  } : undefined;
  const actions = members.filter(m => m.type === 'action') as ActionNode[];
  const events = members.filter(m => m.type === 'event') as EventNode[];
  const constraints = members.filter(m => m.type === 'constraint') as ConstraintNode[];
  const allInterfaces = members.filter(m => m.type === 'interface') as any[];

  const enumMap = new Map<string, string[]>();
  for (const iface of allInterfaces) {
    if (iface?.methods?.length > 0) enumMap.set(iface.name, iface.methods.map((m: any) => m.name));
  }
  currentEnumMap = enumMap;

  const goNameS = goName(speck.name);
  const speckName = speck.name;
  const structName = `${goNameS}Machine`;

  // state enum
  const stateVarType = stateNode?.variables?.[0]?.typeExpr;
  let stateEnumName = `${goNameS}State`;
  if (stateVarType?.type === 'ident' && stateVarType.name) {
    stateEnumName = `${goNameS}${goName(cleanName(stateVarType.name))}`;
  } else if (enumMap.size > 0) {
    const first = enumMap.keys().next().value;
    if (first) stateEnumName = `${goNameS}${goName(first)}`;
  }

  const stateVars: { origName: string; goName: string; typeExpr: any }[] =
    ((stateNode?.variables ?? []) as any[]).map((v: any) => ({
    origName: cleanName(v.name),
    goName: goName(cleanName(v.name)),   // exported so JSON snapshot persistence works
    typeExpr: v.typeExpr,
  }));
  const nameMap = new Map<string, string>();
  for (const v of stateVars) nameMap.set(v.origName, v.goName);
  const stateVarOrigNames = new Set(stateVars.map(v => v.origName));
  const mapVarOrigNames = new Set(stateVars
    .filter(v => v.typeExpr?.type === 'map' || (v.typeExpr?.type === 'ident' && v.typeExpr?.name && /^Map/i.test(v.typeExpr.name)))
    .map(v => v.origName));

  // collect record field renames + record literal casing tables (BEFORE rewrites)
  goFieldRenames = new Map();
  recordTypes = new Map();
  for (const m of members) {
    if (m.type === 'interface' && (m as any).fields) {
      recordTypes.set(goName(m.name), (m as any).fields.map((f: any) => f.name));
      recordFieldTypes.set(cleanName(m.name), new Map((m as any).fields.map((f: any) => [f.name, f.type])));
      for (const f of (m as any).fields) goFieldRenames.set(f.name, goName(f.name));
    }
    if ((m.type as any) === 'type' && (m as any).typeExpr?.type === 'record') {
      const fields = (m as any).typeExpr.fields.map((f: any) => f.name);
      recordTypes.set(goName((m as any).name), fields);
      recordFieldTypes.set(cleanName((m as any).name), new Map((m as any).typeExpr.fields.map((f: any) => [f.name, f.type])));
      for (const f of fields) goFieldRenames.set(f.name, goName(f.name));
    }
  }

  // collect known state values (enum interfaces + string literals compared/emitted)
  const known = new Set<string>();
  for (const vals of enumMap.values()) for (const v of vals) known.add(v);
  // DO NOT infer enums from string literals in actions — this causes
  // type pollution in multi-entity specs. Only explicit interface enums
  // should generate typed constants.
  const knownStateValues = Array.from(known);

  // enum defs
  const enumDefs: string[] = [];
  const seenEnumTypes = new Map<string, string[]>();
  // Seed the state-enum name only when the first state variable's type is
  // actually one of the interface enums. Specs whose first state var is a
  // record (e.g. LlmRouting) would otherwise hijack every enum's constants
  // under the wrong type name.
  const firstVarIsEnum = stateVarType?.type === 'ident' && enumMap.has(cleanName(stateVarType.name));
  if (knownStateValues.length > 0 && firstVarIsEnum) seenEnumTypes.set(stateEnumName, knownStateValues);
  for (const [k, v] of enumMap) seenEnumTypes.set(`${goNameS}${goName(k)}`, v);
  for (const [typeName, values] of seenEnumTypes) {
    enumDefs.push(`type ${typeName} string\n`);
    for (const v of Array.from(new Set(values))) {
      enumDefs.push(`const ${typeName}${goName(v)} ${typeName} = ${JSON.stringify(v)}`);
    }
    enumDefs.push('');
  }

  // value -> typed const name, for lowering bare enum literals in expressions
  enumValueConsts = new Map();
  for (const [typeName, values] of seenEnumTypes) {
    for (const v of values) if (!enumValueConsts.has(v)) enumValueConsts.set(v, `${typeName}${goName(v)}`);
  }

  const recordStructs = allInterfaces
    .filter(iface => iface?.kind === 'record' || (iface?.fields && iface.fields.length > 0))
    .map(iface => {
      const fields = iface.fields.map((f: any) => `${goName(f.name)} ${goType(f.type, speck.name, enumMap)}`).join('; ');
      return `type ${goName(iface.name)} struct { ${fields} }`;
    }).join('\n\n');

  const eventStructs = events.map(e => {
    const fields = e.fields.map(f => `${goName(f.name)} ${goType(f.type, speckName, enumMap)}`).join('; ');
    return `type ${goName(e.name)} struct { ${fields} }`;
  }).join('\n\n');

  const stateFields = stateVars.map(v => `${v.goName} ${goType(v.typeExpr, speckName, enumMap)}`).join('\n\t');

    // init: concrete empties for ALL state vars first (nil maps panic on
  // assignment), then apply explicit init assignments as overrides.
  const defaults = stateVars
    .map(v => `\tm.${v.goName} = ${defaultGoValue(v.typeExpr, speck.name, enumMap)}`)
    .join('\n');
  const overrides = ((initNode?.assignments ?? []) as any[])
    .filter((a: any) => !/^\w*\.(empty|now)/.test(cleanExpr(a.expr)))
    .map((a: any) => {
      const gname = nameMap.get(cleanName(a.name)) || camelCase(cleanName(a.name));
      let expr = rewriteGoExpr(cleanExpr(a.expr), nameMap, mapVarOrigNames, new Set<string>(), stateEnumName, knownStateValues);
      const ml = lowerMapLiteral(expr, stateVarTypes.get(cleanName(a.name)));
      if (ml) expr = ml;
      return `\tm.${gname} = ${expr}`;
    }).join('\n');
  const initBody = overrides ? defaults + '\n' + overrides : defaults;

  // unknown domain functions -> explicit stubs (return type inferred from usage)
  const unknown = new Set<string>();
  const builtin = new Set(['now', 'len', 'length', 'join', 'append', 'mapHas', 'setContains', 'inValues', 'countWhere', 'implies', 'slugify', 'contains', 'has', 'values', 'keys', 'empty', 'size', 'count']);
  const ctxExprs: { text: string; ctx: 'guard' | 'value' | 'emit' | 'return' }[] = [];
  const letVarFn = new Map<string, string>();
  for (const a of actions) {
    for (const st of a.statements) {
      const ctx = (st.type === 'require' || st.type === 'precondition') ? 'guard'
        : st.type === 'emit' ? 'emit' : st.type === 'return' ? 'return' : 'value';
      ctxExprs.push({ text: String((st as any).expr ?? ''), ctx });
      if (st.type === 'ifblock') ctxExprs.push({ text: String((st as any).raw ?? ''), ctx: 'value' });
      if (st.type === 'emit') for (const f of (st as any).fields ?? []) {
        ctxExprs.push({ text: String(f.value), ctx: 'emit' });
      }
      if (st.type === 'assign') ctxExprs.push({ text: String((st as any).target ?? ''), ctx: 'value' });
      if (st.type === 'let') {
        const m = String((st as any).expr ?? '').trim().match(/^([a-z_]\w*)\s*\(/);
        if (m && !builtin.has(m[1])) letVarFn.set(String((st as any).name), m[1]);
      }
      if (st.type === 'ifblock') {
        const raw = String((st as any).raw ?? '');
        for (const lm of raw.matchAll(/let\s+(\w+)\s*:=\s*([a-z_]\w*)\s*\(/g)) {
          if (!builtin.has(lm[2])) letVarFn.set(lm[1], lm[2]);
        }
      }
    }
  }
  for (const c of constraints) ctxExprs.push({ text: String((c as any).expr ?? ''), ctx: 'guard' });

  const numFns = new Set<string>();
  const boolFns = new Set<string>();
  const strFns = new Set<string>();
  for (const { text, ctx } of ctxExprs) {
    for (const m of text.match(/\b([a-z_]\w*)\s*\(/g) ?? []) {
      const fn = m.replace(/\s*\($/, '');
      if (builtin.has(fn)) continue;
      unknown.add(fn);
      if (ctx === 'guard') boolFns.add(fn);
    }
  }
  // let-bound call results: infer return type from how the variable is used
  for (const [v, fn] of letVarFn) {
    const varRe = new RegExp(`\\b${escapeRegex(v)}\\b`);
    for (const { text } of ctxExprs) {
      if (!varRe.test(text)) continue;
      if (new RegExp(`(>=|<=|>|<)\\s*${escapeRegex(v)}\\b`).test(text)
        || new RegExp(`\\b${escapeRegex(v)}\\s*(>=|<=|>|<)`).test(text)) { numFns.add(fn); continue; }
      if (/(==|!=)\s*(true|false)\b/.test(text)) boolFns.add(fn);
    }
    for (const { text } of ctxExprs) {
      if (!varRe.test(text)) continue;
      if (new RegExp(`\\w+\\s*:\\s*${escapeRegex(v)}\\b`).test(text) || new RegExp(`\\w+\\.\\w+\\s*:=\\s*${escapeRegex(v)}\\b`).test(text)) strFns.add(fn);
      // map-key usage implies a string-typed domain function
      if (new RegExp(`\\[\\s*${escapeRegex(v)}\\s*\\]`).test(text)) strFns.add(fn);
    }
  }
  // direct call comparisons: x == fn(...) / fn(...) >= y
  for (const fn of Array.from(unknown)) {
    const callCmp = new RegExp(`(>=|<=|>|<|==|!=)\\s*${escapeRegex(fn)}\\s*\\(|${escapeRegex(fn)}\\s*\\([^)]*\\)\\s*(>=|<=|>|<|==|!=)`);
    for (const { text } of ctxExprs) {
      if (!callCmp.test(text)) continue;
      if (/(==|!=)\s*(true|false)\b/.test(text)) boolFns.add(fn);
      else numFns.add(fn);
    }
  }
  const fnKind = (fn: string): string => numFns.has(fn) ? 'float64' : boolFns.has(fn) ? 'bool' : strFns.has(fn) ? 'string' : 'any';
  currentFnRetTypes = new Map(Array.from(unknown).map(fn => [fn, fnKind(fn)]));
  const stubs = unknown.size > 0
    ? Array.from(unknown).sort().map(fn => {
        const ret = fnKind(fn);
        return `// ${fn} - domain function from the SpeckDL spec. Implement per spec semantics.\nfunc ${fn}(args ...any) ${ret} {\n\tpanic("speckl: domain function not implemented: ${fn}")\n}`;
      }).join('\n\n')
    : '';

  const actionMethods = actions
    .map(a => emitAction(a, nameMap, mapVarOrigNames, goNameS, stateEnumName, knownStateValues, enumMap))
    .join('\n\n');

  const invariantChecks = constraints.map((c, i) => {
    // constraints whose body is comments only are vacuously true
    const cExpr = c.expr.split('\n').map(l => l.replace(/\/\/.*$/, '').trim()).filter(Boolean).join('\n').trim();
    const fname = `Check${goName(c.name || 'Invariant' + i)}`;
    // peel forall prefixes (supports nested forall and .keys/.values suffixes)
    const forallRe = /^forall\s+(\w+)\s+in\s+(\w+)(\.values(?:\(\))?|\.keys(?:\(\))?)?:\s*([\s\S]+)$/;
    const loops: { varName: string; collName: string; mode: 'keys' | 'values' }[] = [];
    let rest = cExpr;
    let fm: RegExpMatchArray | null;
    while ((fm = rest.match(forallRe))) {
      loops.push({ varName: fm[1], collName: fm[2], mode: fm[3] && fm[3].startsWith('.keys') ? 'keys' : 'values' });
      rest = fm[4];
    }
    let body: string;
    if (loops.length > 0) {
      const loopRecords = new Map<string, string>();
      for (const l of loops) {
        const vt = stateVarTypes.get(l.collName);
        if (vt?.type === 'map' && vt.valueType?.type === 'ident') loopRecords.set(l.varName, cleanName(vt.valueType.name));
        if (vt?.type === 'list' && vt.elementType?.type === 'ident') loopRecords.set(l.varName, cleanName(vt.elementType.name));
      }
      const keyVars = new Set(loops.filter(l => l.mode === 'keys').map(l => l.varName));
      const varRef = (v: string) => (keyVars.has(v) ? v : v + 'Val');
      const renameLoopVars = (s2: string) => {
        let out = s2.replace(/\b(\w+)\.(\w+)/g, (m2, obj, f) => {
          const mapped = goFieldRenames.get(f);
          return mapped ? `${obj}.${mapped}` : m2;
        });
        for (const l of loops) {
          // don't rename the machine receiver `m.<stateField>` - only the
          // loop variable's own field accesses
          const stateFields = Array.from(nameMap.values()).join('|');
          out = out.replace(new RegExp(`\\b${escapeRegex(l.varName)}\\b(?!\\.(?:${stateFields})\\b)`, 'g'), varRef(l.varName));
        }
        return out;
      };
      const lines: string[] = [];
      for (let d = 0; d < loops.length; d++) {
        const l = loops[d];
        const vt = stateVarTypes.get(l.collName);
        const gColl = nameMap.get(l.collName) || camelCase(l.collName);
        if (l.mode === 'keys' && vt?.type === 'map') {
          lines.push(`${'\t'.repeat(d + 1)}for ${l.varName} := range m.${gColl} {`);
        } else {
          lines.push(`${'\t'.repeat(d + 1)}for _, ${l.varName}Val := range m.${gColl} {`);
        }
      }
      const depth = loops.length;
      const localNames2 = new Set<string>(loops.map(l => l.varName));
      const bodyLines2: string[] = [];
      let unlowerable = false;
      for (const st of rest.split('\n').map(l2 => l2.trim()).filter(Boolean)) {
        const lm = st.match(/^let\s+(\w+)\s*:=\s*([\s\S]+)$/);
        if (lm) {
          const val = renameLoopVars(goImplications(rewriteGoExpr(lm[2], nameMap, mapVarOrigNames, localNames2, stateEnumName, knownStateValues, loopRecords)));
          const brm = lm[2].trim().match(/^(\w+)\[.+\]$/);
          if (brm) {
            const vt2 = stateVarTypes.get(brm[1]);
            if (vt2?.type === 'map' && vt2.valueType?.type === 'ident') loopRecords.set(lm[1], cleanName(vt2.valueType.name));
          }
          bodyLines2.push(`${'\t'.repeat(depth + 1)}${camelCase(lm[1])} := ${val}`);
          localNames2.add(lm[1]);
        } else {
          const exprGo = renameLoopVars(goImplications(rewriteGoExpr(st, nameMap, mapVarOrigNames, localNames2, stateEnumName, knownStateValues, loopRecords)));
          unlowerable = unlowerable || /\bimplies\(/.test(exprGo) || /\b\w+\s+has\s+\w+\b(?!\()/.test(exprGo);
          bodyLines2.push(`${'\t'.repeat(depth + 1)}if !(${exprGo}) {`);
          bodyLines2.push(`${'\t'.repeat(depth + 2)}return false`);
          bodyLines2.push(`${'\t'.repeat(depth + 1)}}`);
        }
      }
      lines.push(...bodyLines2);
      for (let d = loops.length - 1; d >= 0; d--) lines.push(`${'\t'.repeat(d + 1)}}`);
      if (unlowerable) {
        body = `\t// TODO: manual review - invariant could not be mechanically lowered:\n\t// ${cExpr.replace(/\s+/g, ' ').replace(/\*\//g, '* /')}\n\treturn true`;
      } else {
        lines.push('\treturn true');
        body = lines.join('\n');
      }
    } else {
      if (!cExpr) {
        body = '\treturn true';
      } else {
        body = `\treturn ${goImplications(rewriteGoExpr(cExpr, nameMap, mapVarOrigNames, new Set<string>(), stateEnumName, knownStateValues))}`;
      }
    }
    return `// Invariant ${fname}: ${cExpr.replace(/\s+/g, ' ').slice(0, 90)}\nfunc (m *${structName}) ${fname}() bool {\n${body}\n}`;
  }).join('\n\n');


  const eventLogField = events.length > 0 ? '\n\t// EventLog records every decision (spec events).\n\tEventLog []any' : '';
  const eventStructsBlock = events.length > 0
    ? eventStructs + `\n\n// ${goNameS}Event union marker.\ntype ${goNameS}Event interface{ is${goNameS}Event() }`
    : '';

  const bodyText = [actionMethods, invariantChecks, initBody].join('\n');
  const importNames = ['fmt', 'strings', 'strconv'].filter(i => bodyText.includes(i + '.'));
  if (bodyText.includes('time.')) importNames.push('time');
  const importBlock = importNames.length > 0
    ? 'import (\n' + importNames.map(i => '\t"' + i + '"').join('\n') + '\n)'
    : '';

  return [
    `// Code generated by speckl (go backend) from ${speck.name}.speckdl. DO NOT EDIT BY HAND.`,
    `// Clean-room generated from the SpeckDL specification; contains no third-party code.`,
    `// Domain-function stubs must be implemented per the spec text.`,
    `package ${snakeCase(speck.name)}`,
    '',
    importBlock,
    '',
    enumDefs.join('\n'),
    '',
    recordStructs,
    '',
    eventStructsBlock,
    '',
    `// ${structName} - state machine generated from the SpeckDL specification.`,
    `type ${structName} struct {`,
    `\t${stateFields}${eventLogField}`,
    '}',
    '',
    `// New${goNameS}Machine constructs the machine in its initial state.`,
    `func New${goNameS}Machine() *${structName} {`,
    `\tm := &${structName}{}`,
    initBody.split('\n').map(l => '\t' + l.trim()).join('\n'),
    `\treturn m`,
    '}',
    '',
    actionMethods,
    '',
    invariantChecks,
    ...(stubs ? ['', stubs] : []),
  ].join('\n');
}

// ─── actions ────────────────────────────────────────────────────────

function emitAction(
  action: ActionNode,
  nameMap: Map<string, string>,
  mapVarOrigNames: Set<string>,
  speckName: string,
  stateEnumName: string,
  knownStateValues: string[],
  enumMap: Map<string, string[]>
): string {
  const localNames = new Set(action.params.map(p => cleanName(p.name)));
  const params = action.params
    .map(p => `${camelCase(cleanName(p.name))} ${goType(p.type, speckName, enumMap)}`)
    .join(', ');
  const methodName = goName(action.name);
  const hasReturn = action.statements.some(s => s.type === 'return');
  const nullableParams = new Set(action.params.filter((p: any) => p.type?.nullable).map((p: any) => camelCase(cleanName(p.name))));
  const localRecords = new Map<string, string>();
  for (const p of action.params as any[]) {
    if (p.type?.type === 'ident' && !['Nat','Int','Real','Number','Bool','String','Bytes','Date'].includes(cleanName(p.type.name)) && !currentEnumMap.has(cleanName(p.type.name))) {
      localRecords.set(cleanName(p.name), cleanName(p.type.name));
    }
  }
  const retSig = hasReturn ? '(ret any, err error)' : '(err error)';

  const emitAssign = (s: any): string => {
    const target = String(s.target);
    // nested field assign: mapVar[key].field := val
    const nested = target.match(/^(\w+)\[(.+)\]\.(\w+)$/);
    if (nested) {
      const gname = nameMap.get(cleanName(nested[1])) || camelCase(cleanName(nested[1]));
      const key = rewriteGoExpr(nested[2], nameMap, mapVarOrigNames, localNames, stateEnumName, knownStateValues, localRecords);
      const gfield = goFieldRenames.get(nested[3]) || goName(nested[3]);
      const val = rewriteGoExpr(s.expr, nameMap, mapVarOrigNames, localNames, stateEnumName, knownStateValues, localRecords);
      let v = val;
      const vt = stateVarTypes.get(cleanName(nested[1]));
      const rec = vt?.type === 'map' && vt.valueType?.type === 'ident' ? cleanName(vt.valueType.name) : undefined;
      const ftype = rec ? recordFieldTypes.get(rec)?.get(nested[3]) : undefined;
      if (ftype?.nullable && /^([A-Za-z_]\w*)$/.test(val) && val !== 'nil' && !nullableParams.has(val)) v = `\u0026${val}`;
      // Go: cannot assign through a map to a struct field — read-modify-write
      return [
        `\t{`,
        `\t\tc := m.${gname}[${key}]`,
        `\t\tc.${gfield} = ${v}`,
        `\t\tm.${gname}[${key}] = c`,
        `\t}`,
      ].join('\n');
    }
    const bracket = target.match(/^(\w+)\[(.+)]$/);
    if (bracket) {
      const gname = nameMap.get(cleanName(bracket[1])) || camelCase(cleanName(bracket[1]));
      const key = rewriteGoExpr(bracket[2], nameMap, mapVarOrigNames, localNames, stateEnumName, knownStateValues, localRecords);
      let val = rewriteGoExpr(s.expr, nameMap, mapVarOrigNames, localNames, stateEnumName, knownStateValues, localRecords);
      // inline record literal assigned to a map value: { k: v, ... } -> TypeName{ K: v, ... }
      const vt = stateVarTypes.get(cleanName(bracket[1]));
      if (vt?.type === 'map' && vt.valueType?.type === 'ident') {
        const recName = cleanName(vt.valueType.name);
        const lit = val.match(/^\{\s*([\s\S]*)\s*\}$/);
        if (lit) {
          const inner = lit[1].replace(/(\w+)\s*:/g, (_, f) => `${goName(f)}:`);
          val = `${recName}{ ${inner} }`;
        }
      }
      return `\tm.${gname}[${key}] = ${val}`;
    }
    // local record field assign: localVar.field := val (let-bound local, not a state var)
    const dotted = target.match(/^(\w+)\.(\w+)$/);
    if (dotted && !nameMap.has(cleanName(dotted[1])) && localNames.has(cleanName(dotted[1]))) {
      const gfield = goFieldRenames.get(dotted[2]) || goName(dotted[2]);
      const val = rewriteGoExpr(s.expr, nameMap, mapVarOrigNames, localNames, stateEnumName, knownStateValues, localRecords);
      let v = val;
      const rec = letRecords.get(cleanName(dotted[1]));
      const ftype = rec ? recordFieldTypes.get(rec)?.get(dotted[2]) : undefined;
      if (ftype?.nullable && val !== 'nil') {
        // assigning a non-pointer into a pointer field: take its address
        if (/^([A-Za-z_]\w*)$/.test(val)) {
          if (!currentNullableVars.has(val)) v = `&${val}`;
        } else if (/^\u0000\d+\u0000$/.test(val)) {
          return `\t{ s := ${val}; ${camelCase(cleanName(dotted[1]))}.${gfield} = &s }`;
        } else if (!/[()]$/.test(val)) {
          v = `&${val}`;
        } else {
          return `\t{ s := ${val}; ${camelCase(cleanName(dotted[1]))}.${gfield} = &s }`;
        }
      }
      return `\t${camelCase(cleanName(dotted[1]))}.${gfield} = ${v}`;
    }
    const gname = nameMap.get(cleanName(target)) || camelCase(cleanName(target));
    // let-bound local reassignment: target = val (not a state var)
    if (!nameMap.has(cleanName(target)) && localNames.has(cleanName(target))) {
      const val2 = rewriteGoExpr(s.expr, nameMap, mapVarOrigNames, localNames, stateEnumName, knownStateValues, localRecords);
      return `\t${camelCase(cleanName(target))} = ${val2}`;
    }
    const rawExpr = String(s.expr);
    // SpeckDL append form: list :: elem  ->  list = append(list, elem)
    // (some specs write the list on the left of ::)
    const app = rawExpr.match(/^(\w+)\s*::\s*([\s\S]+)$/);
    if (app && stateVarTypes.get(cleanName(app[1]))?.type === 'list') {
      const listVar = app[1];
      const gname2 = nameMap.get(cleanName(listVar)) || camelCase(cleanName(listVar));
      const elemType = (stateVarsOf(listVar) || '').replace(/^\[\]/, '');
      const elem = fixRecordLiteral(rewriteGoExpr(app[2].trim(), nameMap, mapVarOrigNames, localNames, stateEnumName, knownStateValues, localRecords), elemType);
      return `\tm.${gname2} = append(m.${gname2}, ${elem})`;
    }
    // SpeckDL cons: ELEM :: list  ->  list = append([]Elem{elem}, list)
    const cons = rawExpr.match(/^(.+)\s*::\s*(\w+)$/s);
    if (cons) {
      const listVar = cons[2];
      const gname2 = nameMap.get(cleanName(listVar)) || camelCase(cleanName(listVar));
      const elemType = (stateVarsOf(listVar) || '').replace(/^\[\]/, '');
      const elem = fixRecordLiteral(rewriteGoExpr(cons[1].trim(), nameMap, mapVarOrigNames, localNames, stateEnumName, knownStateValues, localRecords), elemType);
      return `\tm.${gname2} = append([]${elemType}{ ${elem} }, m.${gname2}...)`;
    }
    let val = rewriteGoExpr(rawExpr, nameMap, mapVarOrigNames, localNames, stateEnumName, knownStateValues);
    // Collection .empty() in an action body: lower via the target's own type
    if (/^(List|Map|Set)\.empty\(\)$/.test(val)) {
      const vt2 = stateVarTypes.get(cleanName(target));
      val = defaultGoValue(vt2, speckName, enumMap);
    }
    // Map { "k" -> v, ... } literal: lower via the target's key/value types
    const vtMap = stateVarTypes.get(cleanName(target));
    const mapLit = lowerMapLiteral(val, vtMap);
    if (mapLit) val = mapLit;
    // Nullable (pointer) state var assigned a plain string value: the value
    // must become a pointer (temp var for literals/calls, & for variables)
    const vt3 = stateVarTypes.get(cleanName(target));
    if (vt3?.nullable && goType({ ...vt3, nullable: false }, speckName, enumMap) === 'string') {
      if (val === 'nil') return `\tm.${gname} = nil`;
      if (/^(time\.Now\(\)\.Unix\(\)|nowString\(\))$/.test(val)) {
        return `\t{ s := nowString(); m.${gname} = &s }`;
      }
      if (/^([A-Za-z_]\w*)$/.test(val)) {
        if (!currentNullableVars.has(val)) return `\tm.${gname} = &${val}`;
      } else if (/^\u0000\d+\u0000$/.test(val) || /[()]$/.test(val)) {
        return `\t{ s := ${val}; m.${gname} = &s }`;
      } else {
        return `\tm.${gname} = &${val}`;
      }
    }
    // Nullable (pointer) state var assigned a record literal: take its address
    if (vt3?.nullable && /^([A-Za-z_]\w*)\s*\{/.test(val)) {
      return `\tm.${gname} = &${val}`;
    }
    return `\tm.${gname} = ${val}`;
  };

  // Lower a brace-form conditional captured by the parser pre-pass:
  //   "if <cond> { <stmts> } [else { <stmts> }]"
  const emitIfBlock = (raw: string): string => {
    const open = raw.indexOf('{');
    if (open < 0) return `\t// TODO: conditional not lowered: ${raw.replace(/\n/g, ' ')}`;
    const cond = raw.slice(3, open).trim().replace(/:\s*$/, '');
    // find the top-level '} else {' (if any) and the final top-level '}'
    let depth = 0, elseSplit = -1, closeIdx = -1;
    for (let i = open; i < raw.length; i++) {
      const ch = raw[i];
      if (ch === '{') depth++;
      else if (ch === '}') {
        depth--;
        if (depth === 0) {
          if (raw.startsWith('} else {', i)) { elseSplit = i; i += '} else {'.length - 1; continue; }
          closeIdx = i; break;
        }
      }
    }
    if (closeIdx < 0) return `\t// TODO: conditional not lowered (unbalanced): ${raw.replace(/\n/g, ' ')}`;
    const thenPart = raw.slice(open + 1, elseSplit >= 0 ? elseSplit : closeIdx);
    const elsePart = elseSplit >= 0 ? raw.slice(elseSplit + '} else {'.length, closeIdx) : null;
    const condGo = goImplications(rewriteGoExpr(cond, nameMap, mapVarOrigNames, localNames, stateEnumName, knownStateValues, localRecords));
    const emitStmts = (text: string): string[] => {
      const lines: string[] = [];
      for (const st of splitAssignStmts(text)) {
        const letM = st.match(/^let\s+(\w+)\s*:=\s*([\s\S]*)$/);
        if (letM) {
          const nm = cleanName(letM[1]);
          localNames.add(nm);
          const callM = letM[2].trim().match(/^([a-z_]\w*)\s*\(/);
          if (callM && currentFnRetTypes.get(callM[1]) === 'string') currentLetStringVars.add(nm);
          const val = rewriteGoExpr(letM[2].trim(), nameMap, mapVarOrigNames, localNames, stateEnumName, knownStateValues, localRecords);
          if (/^[A-Za-z_]\w*$/.test(val) && currentNullableVars.has(val)) currentNullableVars.add(nm);
          lines.push(`\t${camelCase(nm)} := ${val}`);
          const litM = letM[2].trim().match(/^([A-Za-z_]\w*)\s*\{/);
          if (litM) letRecords.set(nm, cleanName(litM[1]));
          const brM = letM[2].trim().match(/^(\w+)\[([\s\S]+)\]$/);
          if (brM) {
            const vt = stateVarTypes.get(cleanName(brM[1]));
            if (vt?.type === 'map' && vt.valueType?.type === 'ident') letRecords.set(nm, cleanName(vt.valueType.name));
            else if (vt?.type === 'list' && vt.elementType?.type === 'ident') letRecords.set(nm, cleanName(vt.elementType.name));
          }
          continue;
        }
        const am = st.match(/^([\s\S]+?)\s*:=\s*([\s\S]*)$/);
        if (am) { lines.push(emitAssign({ type: 'assign', target: am[1], expr: am[2] } as any)); continue; }
        lines.push(`\t_ = ${st}`);
      }
      return lines;
    };
    const thenLines = emitStmts(thenPart.trim());
    let out = `\tif ${condGo} {\n${thenLines.join('\n') || '\t'}\n\t}`;
    if (elsePart !== null) {
      const elseLines = emitStmts(elsePart.trim());
      out += ` else {\n${elseLines.join('\n') || '\t'}\n\t}`;
    }
    return out;
  };

  // emit statements in source order so lets declared before guards/assigns
  // that reference them are emitted in the correct sequence
  const letRecords = new Map<string, string>();
  const currentLetStringVars = new Set<string>();
  currentLetStringVars.clear();
  currentNullableVars = new Set(nullableParams);
  const bodyLines: string[] = [];
  for (const s of action.statements as any[]) {
    if (s.type === 'require' || s.type === 'precondition') {
      const expr = goImplications(rewriteGoExpr(s.expr, nameMap, mapVarOrigNames, localNames, stateEnumName, knownStateValues, localRecords));
      bodyLines.push(`\tif !(${expr}) {\n\t\terr = fmt.Errorf("guard failed: ${String(s.expr).replace(/"/g, "'")}")\n\t\treturn\n\t}`);
    } else if (s.type === 'let') {
      localNames.add(s.name);
      const callM = String(s.expr ?? '').trim().match(/^([a-z_]\w*)\s*\(/);
      if (callM && currentFnRetTypes.get(callM[1]) === 'string') currentLetStringVars.add(cleanName(s.name));
      const val = rewriteGoExpr(s.expr, nameMap, mapVarOrigNames, localNames, stateEnumName, knownStateValues, localRecords);
      if (/^[A-Za-z_]\w*$/.test(val) && currentNullableVars.has(val)) currentNullableVars.add(cleanName(s.name));
      const litInt = val.match(/^\d+$/);
      bodyLines.push(`\t${camelCase(s.name)} := ${litInt ? `int64(${val})` : val}`);
      // track the record type of the let-bound local (for nullable field assigns)
      const exprRaw = String(s.expr ?? '');
      const bracketM = exprRaw.match(/^(\w+)\[(.+)\]$/s);
      if (bracketM) {
        const vt = stateVarTypes.get(bracketM[1]);
        if (vt?.type === 'map' && vt.valueType?.type === 'ident') letRecords.set(cleanName(s.name), cleanName(vt.valueType.name));
        else if (vt?.type === 'list' && vt.elementType?.type === 'ident') letRecords.set(cleanName(s.name), cleanName(vt.elementType.name));
      } else {
        const litM = exprRaw.match(/^([A-Za-z_]\w*)\s*\{/);
        if (litM) letRecords.set(cleanName(s.name), cleanName(litM[1]));
      }
    } else if (s.type === 'assign') {
      bodyLines.push(emitAssign(s));
    } else if (s.type === 'ifblock') {
      bodyLines.push(emitIfBlock(String((s as any).raw ?? '')));
    } else if (s.type === 'emit') {
      const fields = ((s.fields ?? []) as any[])
        .map((f: any) => `${goName(f.name)}: ${rewriteGoExpr(f.value, nameMap, mapVarOrigNames, localNames, stateEnumName, knownStateValues, localRecords)}`)
        .join(', ');
      bodyLines.push(`\tm.EventLog = append(m.EventLog, ${goName(s.event)}{ ${fields} })`);
    } else if (s.type === 'return') {
      bodyLines.push(`\tret = ${rewriteGoExpr(s.expr, nameMap, mapVarOrigNames, localNames, stateEnumName, knownStateValues, localRecords)}`);
    }
  }

  let body = bodyLines.length ? bodyLines.join('\n') : '\treturn';
  body += '\n\treturn';

  return `// Execute action: ${action.name}\nfunc (m *${goName(speckName)}Machine) ${methodName}(${params}) ${retSig} {\n${body}\n}`;
}

// ─── handlers (HTTP + htmx surface) ─────────────────────────────────

function emitHandlers(speck: SpeckNode): string {
  const actions = speck.members.filter(m => m.type === 'action') as ActionNode[];
  const structName = `${goName(speck.name)}Machine`;
  const handlers = actions.map(a => {
    const route = `/actions/${snakeCase(a.name)}`;
    const typedFields = a.params
      .map(p => `\t\t\t${goName(p.name)} ${goType(p.type, speck.name, currentEnumMap)} \`json:"${camelCase(cleanName(p.name))}"\``)
      .join('\n');
    const argNames = a.params.map(p => `req.${goName(p.name)}`).join(', ');
    const hasRet = a.statements.some(s => s.type === 'return');
    const call = hasRet
      ? `ret, err := m.${goName(a.name)}(${argNames})`
      : `err := m.${goName(a.name)}(${argNames})`;
    const resp = hasRet
      ? `\t\tjson.NewEncoder(w).Encode(map[string]any{"ok": true, "result": ret})`
      : `\t\tjson.NewEncoder(w).Encode(map[string]any{"ok": true})`;
    return `	// ${a.name} — POST ${route} (htmx: hx-post="${route}")
	mux.HandleFunc("POST ${route}", auth(func(w http.ResponseWriter, r *http.Request) {
		var req struct {
${typedFields}
		}
		if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
			http.Error(w, err.Error(), http.StatusBadRequest)
			return
		}
		${call}
		if err != nil {
			json.NewEncoder(w).Encode(map[string]any{"ok": false, "error": err.Error()})
			return
		}
${resp}
		m.Save()
	}));`;
  }).join('\n\n');

  return `// Code generated by speckl (go backend): HTTP + htmx surface.
//
// Frontend model: Go html/template + htmx. Each spec action gets a POST
// endpoint; htmx forms POST to these endpoints and swap fragments with the
// response. Mount with RegisterHandlers(mux, machine).
//
// Auth: set GB_API_KEY to require X-API-Key on every action call.
// Persistence: set GB_STATE_PATH (default ./state.json) — state snapshots
// are written after every successful mutation and loaded at boot.
package ${snakeCase(speck.name)}

import (
	"encoding/json"
	"net/http"
)

func RegisterHandlers(mux *http.ServeMux, m *${structName}) {
${handlers}

	mux.HandleFunc("GET /healthz", func(w http.ResponseWriter, r *http.Request) {
		json.NewEncoder(w).Encode(map[string]any{"status": "ok", "machine": "${goName(speck.name)}"})
	})

	mux.HandleFunc("GET /state.json", auth(func(w http.ResponseWriter, r *http.Request) {
		json.NewEncoder(w).Encode(m)
	}))
}
`;
}



function emitStore(speck: SpeckNode): string {
  const structName = `${goName(speck.name)}Machine`;
  return `// Code generated by speckl (go backend): JSON snapshot persistence.
package ${snakeCase(speck.name)}

import (
	"encoding/json"
	"net/http"
	"os"
)

// statePath - where the machine snapshot lives (GB_STATE_PATH, default ./state.json).
func statePath() string {
	if p := os.Getenv("GB_STATE_PATH"); p != "" {
		return p
	}
	return "./state.json"
}

// Save writes a full state snapshot (including the event log).
func (m *${structName}) Save() {
	b, err := json.Marshal(m)
	if err != nil {
		return
	}
	os.WriteFile(statePath(), b, 0600)
}

// Load restores a previous state snapshot. Missing file = fresh machine.
func (m *${structName}) Load() {
	b, err := os.ReadFile(statePath())
	if err != nil {
		return
	}
	json.Unmarshal(b, m)
}

// auth - API-key middleware. If GB_API_KEY is unset, requests are allowed
// (single-operator mode). Set GB_API_KEY to lock actions down.
func auth(next http.HandlerFunc) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		key := os.Getenv("GB_API_KEY")
		if key == "" || r.Header.Get("X-API-Key") == key {
			next(w, r)
			return
		}
		http.Error(w, "unauthorized", http.StatusUnauthorized)
	}
}
`;
}



function emitMain(speck: SpeckNode): string {
  const structName = `${goName(speck.name)}Machine`;
  const goNameS = goName(speck.name);
  return `// Code generated by speckl (go backend): deployable service entrypoint.
//
// Env:
//   PORT          listen port (default 8080)
//   GB_API_KEY    if set, actions require X-API-Key header
//   GB_STATE_PATH state file (default ./state.json)
//
// Deploy: ships with a Dockerfile — any container host works (Railway,
// Fly, Compose). Single static binary, SQLite-free by default.
package main

import (
	"log"
	"net/http"
	"os"

	machine "speckl/${snakeCase(speck.name)}"
)

func main() {
	m := machine.New${goNameS}Machine()
	m.Load()

	mux := http.NewServeMux()
	machine.RegisterHandlers(mux, m)

	addr := ":" + orDefault(os.Getenv("PORT"), "8080")
	// compiled UI assets: serve ./static (Elm app.js, css) and ./ui (index.html)
	mux.Handle("GET /static/", http.StripPrefix("/static/", http.FileServer(http.Dir("static"))))
	mux.HandleFunc("GET /", func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path != "/" {
			http.NotFound(w, r)
			return
		}
		b, err := os.ReadFile("ui/index.html")
		if err != nil {
			http.Error(w, "UI not found", http.StatusInternalServerError)
			return
		}
		w.Header().Set("Content-Type", "text/html; charset=utf-8")
		w.Write(b)
	})

	log.Printf("speckl ${snakeCase(speck.name)}: listening on %s", addr)
	log.Fatal(http.ListenAndServe(addr, mux))
}

func orDefault(v, d string) string {
	if v == "" {
		return d
	}
	return v
}

var _ = machine.${structName}{}
`;
}


