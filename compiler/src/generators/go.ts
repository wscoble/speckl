import { AST, SpeckNode, MemberNode, StateNode, InitNode, ActionNode, ConstraintNode, EventNode } from '../parser.js';
import fs from 'fs';
import path from 'path';

/**
 * Generate Go from a SpeckDL spec.
 *
 * Outputs a self-contained Go package with:
 *  - State struct + machine with action methods returning (ret, err)
 *  - Guards (require) become errors; emits append to an event log
 *  - Invariant check methods (read-only)
 *  - Event structs
 *  - handlers.go: HTTP + htmx surface, one POST endpoint per action
 *  - go.mod
 *
 * Clean-room: generated from the SpeckDL specification only.
 */

export function generateGo(ast: AST, outputDir: string): void {
  for (const speck of ast.specks) {
    const pkg = snakeCase(speck.name);
    const speckDir = path.join(outputDir, pkg);
    fs.mkdirSync(speckDir, { recursive: true });

    fs.writeFileSync(path.join(speckDir, 'go.mod'), `module greybeard/${pkg}\n\ngo 1.22\n`);
    fs.writeFileSync(path.join(speckDir, `${pkg}.go`), emitSpeck(speck));
    fs.writeFileSync(path.join(speckDir, 'handlers.go'), emitHandlers(speck));
    fs.writeFileSync(path.join(speckDir, 'prelude.go'), preludeFile.replace('package __prelude', `package ${pkg}`));
    fs.writeFileSync(path.join(speckDir, 'store.go'), emitStore(speck));
    const cmdDir = path.join(speckDir, 'cmd', 'server');
    fs.mkdirSync(cmdDir, { recursive: true });
    fs.writeFileSync(path.join(cmdDir, 'main.go'), emitMain(speck));
    fs.writeFileSync(path.join(speckDir, 'Dockerfile'), emitDockerfile(speck));
    console.log(`Generated Go package: ${speckDir} (machine + handlers + prelude + store + main + Dockerfile)`);
  }
}

