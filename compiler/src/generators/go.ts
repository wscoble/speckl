function goType(t: any, speckName: string, enumMap: Map<string, string[]>): string {
  if (!t) return 'any';
  if ((t.type as any) === 'union' || Array.isArray(t)) {
    // T | null -> *T
    const members: any[] = t.types ?? t;
    const nonNull = members.find((x: any) => !(x.name === 'null' && x.type !== 'ident') && !(x.type === 'ident' && x.name === 'null'));
    if (nonNull) return '*' + goType(nonNull, speckName, enumMap);
    return 'any';
  }
  if (t.type === 'primitive') {
    const map: Record<string, string> = {
      Nat: 'int64', Int: 'int64', Real: 'float64', Number: 'float64',
      Bool: 'bool', String: 'string', Bytes: '[]byte', Date: 'int64',
    };
    const base = map[t.name] || t.name.toLowerCase();
    return (t as any).nullable ? '*' + base : base;
  }
  if (t.type === 'list') return `[]${goType(t.elementType, speckName, enumMap)}`;
  if (t.type === 'set') return `map[${goType(t.elementType, speckName, enumMap)}]bool`;
  if (t.type === 'map') return `map[${goType(t.keyType, speckName, enumMap)}]${goType(t.valueType, speckName, enumMap)}`;
  if (t.type === 'record') {
    const fields = t.fields.map((f: any) => `${goName(f.name)} ${goType(f.type, speckName, enumMap)}`).join('; ');
    return `struct { ${fields} }`;
  }
  if (t.type === 'ident') {
    const raw = cleanName(t.name);
    if (enumMap?.has(raw)) return `${goName(speckName)}${goName(raw)}`;
    const prim: Record<string, string> = { Nat: 'int64', Int: 'int64', Bool: 'bool', String: 'string', Date: 'int64', Real: 'float64', Number: 'float64' };
    if (prim[raw]) return t.nullable ? '*' + prim[raw] : prim[raw];
    const opt = raw.match(/^Option[_(]\s*(\w+)\s*\)?$/);
    if (opt) return '*' + (prim[opt[1]] || goName(opt[1]));
    return t.nullable ? '*' + goName(raw) : goName(raw);
  }
  return 'any';
}

