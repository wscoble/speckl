// strip a trailing // comment (outside string literals) from an expression
function stripComment(expr: string): string {
  let inStr = false; let esc = false;
  for (let i = 0; i < expr.length - 1; i++) {
    const ch = expr[i];
    if (esc) { esc = false; continue; }
    if (ch === '\\') { esc = true; continue; }
    if (ch === '"') inStr = !inStr;
    if (!inStr && ch === '/' && expr[i + 1] === '/') return expr.slice(0, i).trim();
  }
  return expr;
}

function rewriteGoExpr(
  expr: string,
  nameMap: Map<string, string>,
  mapVarOrigNames: Set<string>,
  localNames: Set<string>,
  stateEnumName: string,
  knownStateValues: string[],
  localRecords: Map<string, string> = new Map()
): string {
  expr = stripComment(expr);
  // existential quantifier: (not) exists v in coll(.values())?: pred
  const em = expr.match(/(not\s+)?exists\s+(\w+)\s+in\s+([\w.]+?)(?:\.values(?:\(\))?)?:\s*([\s\S]+)$/);
  if (em) {
    let origName = em[3].replace(/^m\./, '');
    for (const [orig, gn] of nameMap) { if (em[3] === gn) { origName = orig; break; } }
    const vt = stateVarTypes.get(origName);
    let rec = 'any';
    if (vt?.type === 'map' && vt.valueType?.type === 'ident') rec = goType(vt.valueType, '', currentEnumMap);
    else if (vt?.type === 'list' && vt.elementType?.type === 'ident') rec = goType(vt.elementType, '', currentEnumMap);
    const helper = vt?.type === 'list' ? 'listAnyMatch' : 'anyMatch';
    expr = `${em[1] ? '!' : ''}${helper}(${em[3]}, func(${em[2]} ${rec}) bool { return ${em[4]} })`;
  }
  let g = expr;
  // Protect string literals: the chain below rewrites bare words (`not`,
  // enum values, `null`) and must never touch string content.
  const stringLits: string[] = [];
  g = g.replace(/"(?:[^"\\]|\\.)*"/g, m2 => { stringLits.push(m2); return `\u0000${stringLits.length - 1}\u0000`; });
  // count(coll, v => pred) -> countWhere(<coll>, func(v T) bool { return pred })
  // Balanced-paren scan: the predicate may contain nested calls, so the
  // old first-')' regex truncated it (syntax errors in the emitted Go).
  // The predicate is emitted verbatim and lowered by the chain below.
  if (/\bcount\(/.test(g)) {
    let out = '';
    let i = 0;
    while (i < g.length) {
      if (!/^\bcount\(/.test(g.slice(i))) { out += g[i]; i++; continue; }
      let depth = 0, close = -1, inStr = false;
      for (let k = i; k < g.length; k++) {
        const ch = g[k];
        if (ch === '"') inStr = !inStr;
        if (inStr) continue;
        if (ch === '(') depth++;
        else if (ch === ')') { depth--; if (depth === 0) { close = k; break; } }
      }
      if (close < 0) { out += g[i]; i++; continue; }
      const inner = g.slice(i + 'count('.length, close);
      let d2 = 0, b2 = 0, cIdx = -1;
      for (let k = 0; k < inner.length; k++) {
        const ch = inner[k];
        if (ch === '(' || ch === '<' || ch === '[') d2++;
        else if (ch === ')' || ch === '>' || ch === ']') d2--;
        else if (ch === '{') b2++;
        else if (ch === '}') b2--;
        else if (ch === ',' && d2 === 0 && b2 === 0) { cIdx = k; break; }
      }
      const lm = cIdx >= 0 ? inner.slice(cIdx + 1).trim().match(/^(\w+)\s*=>\s*([\s\S]+)$/) : null;
      if (cIdx < 0 || !lm) { out += g.slice(i, close + 1); i = close + 1; continue; }
      const coll = inner.slice(0, cIdx).trim();
      const baseVar = coll.replace(/\.values\(\)|\.keys\(\)/g, '').trim();
      const vt = stateVarTypes.get(baseVar) || stateVarTypes.get(cleanName(baseVar));
      let elemT = 'any';
      if (vt?.type === 'map' && vt.valueType) elemT = goType(vt.valueType, '', currentEnumMap);
      else if (vt?.type === 'list' && vt.elementType) elemT = goType(vt.elementType, '', currentEnumMap);
      out += `countWhere(${coll.replace(/\.values\(\)|\.keys\(\)/g, '')}, func(${lm[1]} ${elemT}) bool { return ${lm[2].trim()} })`;
      i = close + 1;
    }
    g = out;
  }

  const lengthLower = (arg: string): string => {
    const dm = arg.trim().match(/^([A-Za-z_]\w*)\.([A-Za-z_]\w*)$/);
    if (dm) {
      const rec = localRecords.get(dm[1]);
      let ft = rec ? recordFieldTypes.get(rec)?.get(dm[2]) : undefined;
      // the base object may be a state variable holding a record
      if (!ft) {
        const vt = stateVarTypes.get(dm[1]);
        if (vt?.type === 'ident') ft = recordFieldTypes.get(cleanName(vt.name))?.get(dm[2]);
      }
      const base = goType({ ...ft, nullable: false }, '', new Map());
      // anyLen handles plain strings and *string (nil-safe) alike; int64
      // because Nat values compare against it
      if (ft && base === 'string') return `int64(anyLen(${arg}))`;
    }
    return `int64(len(${arg}))`;
  };
  const shouldPrefix = (ident: string) => nameMap.has(ident) && !localNames.has(ident);
  const goify = (ident: string) => nameMap.has(ident) && !localNames.has(ident) ? `m.${nameMap.get(ident)}` : ident;

  g = g
    .replace(/Date\.now\(\)\.toString\(\)/g, 'nowString()')
    .replace(/Date\.now\(\)/g, 'time.Now().Unix()')
    .replace(/\bnow\(\)/g, 'time.Now().Unix()')
    .replace(/\btoInt\(([^)]+)\)/g, 'toInt($1)')
    .replace(/\blength\(([^)]+)\)/g, (_, a) => lengthLower(a))
    .replace(/\blen\(([^)]+)\)/g, (_, a) => lengthLower(a))
    .replace(/\bjoin\(([^,]+),\s*([^)]+)\)/g, 'strings.Join($1, $2)')
    .replace(/\bappend\(([^,]+),\s*([^)]+)\)/g, 'append($1, $2)')
    .replace(/(\w+)\.has\(([^)]+)\)/g, 'mapHas($1, $2)')
    .replace(/\((\w+)\[([^\]]+)\]\)\.has\(([^)]+)\)/g, (_m, coll, key, v) => {
      const vt = stateVarTypes.get(cleanName(coll));
      const isList = vt?.type === 'map' && vt.valueType?.type === 'list';
      return isList ? `listContains(${coll}[${key}], ${v})` : `mapHas(${coll}[${key}], ${v})`;
    })
    .replace(/([\w.]+)\.contains\(([^)]+)\)/g, 'listContains($1, $2)')
    .replace(/\bcount\(([^,]+),\s*(\w+)\s*=>\s*([^)]+)\)/g, 'countWhere($1, func($2 any) bool { return $3 })');
// (legacy count lowering superseded by the balanced-paren scanner above)

  // state enum literals -> typed consts (skip field accesses `x.passed`,
  // record-literal keys `registered:`, and quoted strings)
  for (const [val, constName] of enumValueConsts) {
    g = g.replace(new RegExp('(?<![.\\w])' + escapeRegex(val) + '(?![\\w":])', 'g'), constName);
  }

  // identifier prefixing
  g = g.split(/([\s()\[\]{}+\-*/=<>!&|.,;:'"`]+)/).map(tok => {
    if (/^(true|false|nil|null|not|and|or|in|notIn|old|forall|let|if|else|time|fmt|strings)$/.test(tok)) return tok;
    if (/^\d+(\.\d+)?$/.test(tok)) return tok;
    if (/^[a-zA-Z_]\w*$/.test(tok) && shouldPrefix(tok)) return goify(tok);
    return tok;
  }).join('');
  g = g.replace(/\]\.m\.(\w+)/g, '].$1');

  // speckdl patterns -> go
  g = g
    .replace(/([\w.\u0000]+)\.startsWith\(([^()]*)\)/g, 'strings.HasPrefix($1, $2)')
    .replace(/([\w.\u0000]+)\.endsWith\(([^()]*)\)/g, 'strings.HasSuffix($1, $2)')
    .replace(/([\w.\u0000]+)\s+starts with\s+("[^"]*"|\u0000\d+\u0000|[\w.]+)/g, 'strings.HasPrefix($1, $2)')
    .replace(/([\w.\u0000]+)\s+ends with\s+("[^"]*"|\u0000\d+\u0000|[\w.]+)/g, 'strings.HasSuffix($1, $2)')
    .replace(/(\w+)\.append\(([^()]*)\)/g, 'append($1, $2)')
    .replace(/(\w+)\s+notIn\s+(\w+)\.keys/g, '!mapHas($2, $1)')
    .replace(/(\w+)\s+in\s+(\w+)\.keys/g, 'mapHas($2, $1)')
    .replace(/(\w+)\s+notIn\s+(\w+)\.values/g, '!inValues($2, $1)')
    .replace(/(\w+)\s+in\s+(\w+)\.values/g, 'inValues($2, $1)')
    .replace(/\bnot\s*\(/g, '!(')
    .replace(/old\(([^()]*(?:\([^()]*\)[^()]*)*)\)/g, '$1')
    .replace(/\.size\(\)/g, '.len')
    .replace(/\b===\b/g, '==')
    .replace(/([A-Za-z_]\w*)\s*(==|!=)\s*null\b/g, (m2, v, op) =>
      currentLetStringVars.has(v) ? `${v} ${op} ""` : m2);

  // bare map var bracket access -> m.field[k]
  for (const mapVar of mapVarOrigNames) {
    const gname = nameMap.get(mapVar) || camelCase(mapVar);
    const bare = new RegExp(`(?<![\\w.])${escapeRegex(mapVar)}\\[`, 'g');
    g = g.replace(bare, `m.${gname}[`);
  }

  // set membership: target in { "a", "b", "c" } -> (target == "a" || target == "b" || target == "c")
  g = g.replace(/([\w.]+)\s+in\s+\{([^}]+)\}/g, (_, ident, values) => {
    const vals = values.split(',').map((v: string) => v.trim().replace(/"/g, ''));
    return '(' + vals.map((v: string) => `${ident} == ${JSON.stringify(v)}`).join(' || ') + ')';
  });

  // array membership: target in [ "a", "b" ] -> (target == "a" || target == "b")
  g = g.replace(/([\w.]+)\s+in\s+\[([^\]]+)\]/g, (_, ident, values) => {
    const vals = values.split(',').map((v: string) => v.trim());
    return '(' + vals.map((v: string) => `${ident} == ${v}`).join(' || ') + ')';
  });

  // nullable record fields compared with string literals deref the pointer
  // (the enclosing implies/|| guards nil first; Go short-circuits)
  g = g.replace(/([A-Za-z_]\w*)\.([A-Za-z_]\w*)\s*(==|!=)\s*(\u0000\d+\u0000)/g, (m2, o, f, op, ph) => {
      const rec = localRecords.get(o);
      const ft = rec ? recordFieldTypes.get(rec)?.get(f) : undefined;
      if (ft?.nullable && goType({ ...ft, nullable: false }, '', new Map()) === 'string') {
        return `*${o}.${goFieldRenames.get(f) || goName(f)} ${op} ${ph}`;
      }
      return m2;
    });

  // non-nullable record fields cannot compare against nil; compare with ""
  g = g.replace(/([A-Za-z_]\w*)\.([A-Za-z_]\w*)\s*(==|!=)\s*null\b/g, (m2, o, f, op) => {
      const rec = localRecords.get(o);
      const ft = rec ? recordFieldTypes.get(rec)?.get(f) : undefined;
      if (ft && !ft.nullable && goType({ ...ft, nullable: false }, '', new Map()) === 'string') {
        return `${o}.${goFieldRenames.get(f) || goName(f)} ${op} ""`;
      }
      return m2;
    })
    .replace(/\bnull\b/g, 'nil')
    .replace(/([\w.]+)\.values\(\)/g, 'mapValues($1)')
    .replace(/([\w.]+)\.keys\(\)/g, 'mapKeys($1)');

  // record-field string comparisons with mixed nullability: deref the
  // nullable side (implies guards usually precede; Go short-circuits ||)
  g = g.replace(/([\w.]+)\.([A-Za-z_]\w*)\s*(==|!=)\s*([\w.]+)\.([A-Za-z_]\w*)/g, (m2, o1, f1, op, o2, f2) => {
    const fieldTypeOf = (obj: string, field: string): any => {
      const rec = localRecords.get(obj);
      if (rec) return recordFieldTypes.get(rec)?.get(field);
      // machine-prefixed state vars: m.<GoName> -> raw state name
      let vt = stateVarTypes.get(obj);
      if (!vt && obj.startsWith('m.')) {
        const rev = new Map(Array.from(nameMap).map(([raw, gn]) => [gn, raw]));
        const rawName = rev.get(obj.slice(2));
        if (rawName !== undefined) vt = stateVarTypes.get(rawName);
      }
      if (vt?.type === 'ident') return recordFieldTypes.get(cleanName(vt.name))?.get(field);
      if (vt?.type === 'record') {
        for (const f of (vt.fields || [])) if (f.name === field) return f.type;
      }
      return undefined;
    };
    const t1 = fieldTypeOf(o1, f1);
    const t2 = fieldTypeOf(o2, f2);
    if (!t1 || !t2) return m2;
    const isStr = (t: any) => goType({ ...t, nullable: false }, '', new Map()) === 'string';
    if (!isStr(t1) || !isStr(t2)) return m2;
    const d1 = t1.nullable ? '*' : '';
    const d2 = t2.nullable ? '*' : '';
    if (!d1 && !d2) return m2;
    return `${d1}${o1}.${goFieldRenames.get(f1) || goName(f1)} ${op} ${d2}${o2}.${goFieldRenames.get(f2) || goName(f2)}`;
  });

  // implies -> !(p) || (q)
  let changed = true;
  while (changed) {
    changed = false;
    g = g.replace(/implies\s*\(([^,()]*(?:\([^()]*\)[^()]*)*),\s*([^()]*(?:\([^()]*\)[^()]*)*)\)/g, (_, p, q) => {
      changed = true;
      return `(!(${p.trim()}) || (${q.trim()}))`;
    });
  }
  g = g.replace(/\bnot\s+([a-zA-Z_]\w*)/g, '!$1');
  // forall cannot be an expression in Go; lower at the invariant-statement level.
  // Any residual forall is surfaced as a visible TODO, never silently dropped.
  if (/forall/.test(g)) g = `/* UNLOWERED forall - manual attention required: ${g.replace(/\*\//g, '* /')} */ true`;
  // nullable string comparisons: a.x > b.y -> strCmp(a.x, b.y) > 0
  g = g.replace(/([A-Za-z_]\w*)\.([A-Za-z_]\w*)\s*(>=|<=|>|<)\s*([A-Za-z_]\w*)\.([A-Za-z_]\w*)/g, (m2, o1, f1, op, o2, f2) => {
    const r1 = localRecords.get(o1);
    const r2 = localRecords.get(o2);
    const t1 = r1 ? recordFieldTypes.get(r1)?.get(f1) : undefined;
    const t2 = r2 ? recordFieldTypes.get(r2)?.get(f2) : undefined;
    const isStr = (t: any) => !!t && goType({ ...t, nullable: false }, '', new Map()) === 'string';
    const isPtr = (t: any) => !!t?.nullable;
    if (isStr(t1) && isStr(t2)) {
      const a = `${o1}.${goFieldRenames.get(f1) || goName(f1)}`;
      const b = `${o2}.${goFieldRenames.get(f2) || goName(f2)}`;
      const l = isPtr(t1) ? a : `&${a}`;
      const r = isPtr(t2) ? b : `&${b}`;
      return `strCmp(${l}, ${r}) ${op} 0`;
    }
    return m2;
  });

  // record field casing: .column -> .Column (known record fields)
  for (const [lower, G] of goFieldRenames) {
    g = g.replace(new RegExp(`\\.${lower}\\b`, 'g'), `.${G}`);
  }
  // record literal field casing: Project { projectId: v } -> Project { ProjectId: v }
  for (const [typeName, fields] of recordTypes) {
    const fieldKeys = fields.map(f => escapeRegex(f)).join('|');
    const re = new RegExp(`\\b${typeName}\\s*\\{([^{}]*)\\}`, 'g');
    g = g.replace(re, (m2, inner) => {
      // case field names, then wrap nullable-string field values with strPtr
      const cased = inner.replace(new RegExp(`\\b(${fieldKeys})\\s*:`, 'g'), (_m: string, f: string) => `${goName(f)}:`);
      const ftmapRaw = recordFieldTypes.get(cleanName(typeName));
      if (!ftmapRaw) return `${typeName}{ ${cased} }`;
      // case-insensitive field-type lookup (the pass just cased field names)
      const ftmap = new Map(Array.from(ftmapRaw).map(([k, v]) => [k.toLowerCase(), v]));
      // split at top-level commas (honoring strings)
      const parts: string[] = [];
      let d = 0, inStr = false, start = 0;
      for (let k = 0; k < cased.length; k++) {
        const ch = cased[k];
        if (ch === '"') inStr = !inStr;
        if (inStr) continue;
        if (ch === '(' || ch === '[' || ch === '{') d++;
        else if (ch === ')' || ch === ']' || ch === '}') d--;
        else if (ch === ',' && d === 0) { parts.push(cased.slice(start, k)); start = k + 1; }
      }
      parts.push(cased.slice(start));
      const wrapped = parts.map(part => {
        const pm = part.match(/^\s*([A-Za-z_]\w*)\s*:\s*([\s\S]*)$/);
        if (!pm) return part;
        const ft = ftmap.get(pm[1].toLowerCase());
        const v = pm[2].trim();
        if (ft?.nullable && goType({ ...ft, nullable: false }, '', new Map()) === 'string'
            && v !== 'nil' && !(v.match(/^[A-Za-z_]\w*$/) && currentNullableVars.has(v))) {
          return `${goName(pm[1])}: strPtr(${v})`;
        }
        return part;
      });
      return `${typeName}{ ${wrapped.join(', ')} }`;
    });
  }
  g = g.replace(/\u0000(\d+)\u0000/g, (_m, n) => stringLits[+n]);
  return g.trim();
}

function goImplications(expr: string): string {
  let e = expr; let changed = true;
  while (changed) {
    changed = false;
    let out = '';
    let i = 0;
    while (i < e.length) {
      if (/^\bimplies\(/.test(e.slice(i))) {
        let depth = 0, close = -1;
        for (let k = i; k < e.length; k++) {
          if (e[k] === '(') depth++;
          else if (e[k] === ')') { depth--; if (depth === 0) { close = k; break; } }
        }
        if (close < 0) { out += e[i]; i++; continue; }
        const inner = e.slice(i + 'implies('.length, close);
        let d = 0, cIdx = -1;
        for (let k = 0; k < inner.length; k++) {
          if (inner[k] === '(') d++;
          else if (inner[k] === ')') d--;
          else if (inner[k] === ',' && d === 0) { cIdx = k; break; }
        }
        if (cIdx < 0) { out += e.slice(i, close + 1); i = close + 1; continue; }
        out += `(!(${inner.slice(0, cIdx).trim()}) || (${inner.slice(cIdx + 1).trim()}))`;
        changed = true;
        i = close + 1;
        continue;
      }
      out += e[i]; i++;
    }
    e = out;
  }
  // infix implies: A implies B -> (!(A) || (B))  (split at paren depth 0, recursive)
  const lowerInfixImplies = (s: string): string => {
    let depth = 0;
    for (let i = 0; i < s.length; i++) {
      const ch = s[i];
      if (ch === '(') depth++;
      else if (ch === ')') depth--;
      else if (depth === 0 && s.startsWith('implies', i)
        && (i === 0 || /\s/.test(s[i - 1]))
        && (s[i + 7] === undefined || /\s/.test(s[i + 7]))) {
        const left = lowerInfixImplies(s.slice(0, i).trim());
        const right = lowerInfixImplies(s.slice(i + 7).trim());
        return `(!(${left}) || (${right}))`;
      }
    }
    return s;
  };
  e = lowerInfixImplies(e);
  e = e.replace(/\bnot\s+([a-zA-Z_]\w*)/g, '!$1');
  e = e.replace(/\bor\b/g, '||').replace(/\band\b/g, '&&');
  return e;
}

