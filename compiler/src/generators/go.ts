// ─── helpers ────────────────────────────────────────────────────────

function memberKey(m: MemberNode): string {
  if (m.type === 'action') return `action:${m.name}`;
  if (m.type === 'event') return `event:${m.name}`;
  if (m.type === 'interface') return `interface:${m.name}`;
  if (m.type === 'state') return 'state';
  if (m.type === 'init') return 'init';
  if (m.type === 'provenance') return 'provenance';
  if (m.type === 'bom') return 'bom';
  if (m.type === 'input') return 'input';
  if (m.type === 'output') return 'output';
  if (m.type === 'verify') return `verify:${(m as any).temporalExpr || ''}`;
  if (m.type === 'constraint') return `constraint:${(m as any).expr || ''}`;
  if (m.type === 'oneof') return `oneof:${(m as any).name || ''}`;
  if (m.type === 'transition') return `transition:${(m as any).name || ''}`;
  if (m.type === 'service') return `service:${(m as any).name || ''}`;
  return m.type;
}

function isEmptyStub(m: MemberNode): boolean {
  if (m.type === 'state') return m.variables.length === 0;
  if (m.type === 'init') return m.assignments.length === 0;
  if (m.type === 'action') return m.statements.length === 0;
  if (m.type === 'event') return m.fields.length === 0;
  if (m.type === 'interface') return m.methods.length === 0;
  if (m.type === 'provenance') return m.clauses.length === 0;
  if (m.type === 'bom') return !m.compiler && !m.solver && !m.runtime;
  return false;
}

function cleanName(s: string): string { return s.replace(/,$/, '').trim(); }
function cleanExpr(s: string): string { return s.replace(/,$/, '').trim(); }
function escapeRegex(s: string): string { return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }

// Split a brace-form branch body into top-level statements. A statement
// starts at each depth-0 `:=` (walking back to the lvalue token start, or
// to a `let` keyword). Record-literal `field:` pairs sit inside braces and
// are never statement boundaries.
function splitAssignStmts(text: string): string[] {
  const starts: number[] = [];
  let depth = 0;
  let inStr = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (ch === '"') inStr = !inStr;
    if (inStr) continue;
    if (ch === '{' || ch === '[' || ch === '(') depth++;
    else if (ch === '}' || ch === ']' || ch === ')') depth--;
    else if (ch === ':' && depth === 0 && text[i + 1] === '=') {
      let j = i - 1;
      while (j >= 0 && text[j] === ' ') j--;
      while (j >= 0 && /[\w\]\[.]/.test(text[j])) j--;
      const before = text.slice(0, j + 1).trimEnd();
      if (before.endsWith('let')) j = before.length - 3;
      starts.push(j + 1);
    }
  }
  const stmts: string[] = [];
  for (let k = 0; k < starts.length; k++) {
    const end = k + 1 < starts.length ? starts[k + 1] : text.length;
    const st = text.slice(starts[k], end).trim();
    if (st) stmts.push(st);
  }
  return stmts;
}

function goName(s: string): string {
  return s.split(/[^a-zA-Z0-9]+/).filter(Boolean)
    .map(w => w.charAt(0).toUpperCase() + w.slice(1)).join('');
}
function camelCase(s: string): string {
  const c = goName(s);
  return c.charAt(0).toLowerCase() + c.slice(1);
}
function snakeCase(s: string): string {
  return s.replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2')
    .replace(/([a-z\d])([A-Z])/g, '$1_$2')
    .replace(/([a-zA-Z])(\d)/g, '$1_$2')
    .replace(/[^a-zA-Z0-9_]/g, '_')
    .toLowerCase()
    .replace(/_+/g, '_').replace(/^_|_$/g, '');
}

function defaultGoValue(typeExpr: any, speckName: string = '', enumMap: Map<string, string[]> = new Map()): string {
  if (!typeExpr) return 'nil';
  if (typeExpr.nullable) return 'nil';
  if (typeExpr.type === 'ident' && enumMap?.has(cleanName(typeExpr.name))) {
    const vals = enumMap.get(cleanName(typeExpr.name))!;
    if (vals.length > 0) return `${goName(speckName)}${goName(cleanName(typeExpr.name))}${goName(vals[0])}`;
    return 'nil';
  }
  if (typeExpr.type === 'primitive') {
    switch (typeExpr.name) {
      case 'Nat': case 'Int': case 'Date': return '0';
      case 'Real': case 'Number': return '0.0';
      case 'Bool': return 'false';
      case 'String': return '""';
      default: return 'nil';
    }
  }
  if (typeExpr.type === 'ident') {
    const gn = goName(cleanName(typeExpr.name));
    if (recordTypes.has(gn)) return `${gn}{}`;
  }
  if (typeExpr.type === 'list') return `[]${goType(typeExpr.elementType, '', new Map())}{}`;
  if (typeExpr.type === 'set') return `map[${goType(typeExpr.elementType, '', new Map())}]bool{}`;
  if (typeExpr.type === 'map') return `map[${goType(typeExpr.keyType, '', new Map())}]${goType(typeExpr.valueType, '', new Map())}{}`;
  return 'nil';
}