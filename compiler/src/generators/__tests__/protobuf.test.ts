// src/generators/__tests__/protobuf.test.ts
//
// Tests for the protobuf (.proto3) backend generator. The generator must:
//   - Emit valid proto3 syntax with syntax = "proto3";
//   - Map SpeckDL types to proto3 types (String→string, Nat→uint64, Bool→bool, etc.)
//   - Emit interface records as proto3 messages
//   - Emit interface enums as proto3 enums (with UNSPECIFIED = 0 + prefixed variants)
//   - Emit events as messages (with optional event_suffix)
//   - Emit state blocks as StateSnapshot messages
//   - Emit transition blocks with inline oneof payload
//   - Emit service blocks with rpc methods
//   - Use deterministic alphabetical field numbering (byte-stable)
//   - Support Map<K,V> → map<K,V> proto syntax
//   - Support List<T> → repeated T proto syntax
//   - Support Set<T> → repeated T proto syntax
//   - Populate option go_package from speck metadata
//   - Populate package from proto_package directive
//   - Parse `service { rpc X(...) returns (...); }` syntax cleanly

import { describe, it, expect } from 'vitest';
import { join } from 'path';
import { mkdtempSync, readFileSync, rmSync, writeFileSync, existsSync } from 'fs';
import { tmpdir } from 'os';
import { parseSpeckContent, parseSpeckFile } from '../../parser.js';
import { generateProtobuf } from '../protobuf.js';

// ─── Helpers ──────────────────────────────────────────────

function compileProto(src: string, speckName?: string): string {
  const filePath = '/tmp/speckl-protobuf-test.speckdl';
  writeFileSync(filePath, src);
  const ast = parseSpeckFile(filePath);
  const tmp = mkdtempSync(join(tmpdir(), 'speckl-proto-'));
  try {
    generateProtobuf(ast, tmp);
    const name = speckName || ast.specks[0].name;
    const protoPath = join(tmp, snakeCaseFile(name) + '.proto');
    if (!existsSync(protoPath)) {
      // List files to help debug
      const { readdirSync } = require('fs');
      throw new Error(`Expected proto file not found: ${protoPath}. Files in tmp: ${readdirSync(tmp).join(', ')}`);
    }
    return readFileSync(protoPath, 'utf-8');
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

// The generator uses snakeCase for filenames
function snakeCaseFile(s: string): string {
  return s
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2')
    .toLowerCase();
}

function parseInline(src: string) {
  return parseSpeckContent(src);
}

// ─── Tests ─────────────────────────────────────────────────

describe('Protobuf backend: basic structure', () => {
  it('emits valid proto3 syntax header', () => {
    const proto = compileProto(`
speck ToggleSwitch {
  state {
    isOn: Bool
  }
}
`);
    expect(proto).toContain('syntax = "proto3";');
    expect(proto).toContain('// Auto-generated by speckl-compile');
    expect(proto).toContain('DO NOT EDIT MANUALLY');
  });

  it('emits package from proto_package directive', () => {
    const proto = compileProto(`
speck MySpec {
  proto_package: "com.example.v1"
  state {
    count: Nat
  }
}
`);
    expect(proto).toContain('package com.example.v1;');
  });

  it('emits default package when no proto_package specified', () => {
    const proto = compileProto(`
speck SimpleSpec {
  state {
    value: Nat
  }
}
`);
    expect(proto).toContain('package speckl.simple_spec.v1;');
  });

  it('emits option go_package from go_package directive', () => {
    const proto = compileProto(`
speck MySpec {
  proto_package: "com.example.v1"
  go_package: "github.com/foo/bar/proto/v1;barv1"
  state {
    count: Nat
  }
}
`);
    expect(proto).toContain('option go_package = "github.com/foo/bar/proto/v1;barv1";');
  });

  it('emits default go_package when not specified', () => {
    const proto = compileProto(`
speck SimpleSpec {
  state {
    value: Nat
  }
}
`);
    expect(proto).toContain('option go_package =');
    // Default go_package follows the pattern github.com/sscoble/<name>/proto/<name>/v1;<name>v1
    expect(proto).toContain('github.com/sscoble/simple_spec/proto/simple_spec/v1');
  });
});

