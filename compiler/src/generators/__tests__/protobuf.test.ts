describe('Protobuf backend: messages from interface records', () => {
  it('emits interface records as proto3 messages', () => {
    const proto = compileProto(`
speck RecordTest {
  interface Person {
    name: String,
    age: Nat
  }
}
`);
    expect(proto).toContain('message Person {');
    expect(proto).toContain('string name =');
    expect(proto).toContain('uint64 age =');
  });

  it('uses deterministic alphabetical field numbering', () => {
    const proto = compileProto(`
speck FieldOrderTest {
  interface Record {
    zebra: String,
    apple: Nat,
    mango: Bool
  }
}
`);
    // Fields should be numbered alphabetically: apple=1, mango=2, zebra=3
    const lines = proto.split('\n');
    const appleLine = lines.find(l => l.includes('apple ='));
    const mangoLine = lines.find(l => l.includes('mango ='));
    const zebraLine = lines.find(l => l.includes('zebra ='));
    expect(appleLine).toContain('= 1;');
    expect(mangoLine).toContain('= 2;');
    expect(zebraLine).toContain('= 3;');
  });
});

