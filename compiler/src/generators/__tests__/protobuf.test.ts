describe('Protobuf backend: transitions with oneof payload', () => {
  it('emits transition message with oneof payload block', () => {
    const proto = compileProto(`
speck TransitionTest {
  event Create {
    name: String
  }
  event Delete {
    id: Nat
  }
  oneof TransitionPayload {
    create: Create,
    delete: Delete
  }
  interface TransitionType {
    Create,
    Delete
  }
  transition Transition {
    type: TransitionType,
    payload: TransitionPayload,
    hlc: Bytes
  }
}
`);
    expect(proto).toContain('message Transition {');
    expect(proto).toContain('TransitionType type = 1;');
    expect(proto).toContain('oneof payload {');
    expect(proto).toContain('Create create = 10;');
    expect(proto).toContain('Delete delete = 11;');
    expect(proto).toContain('bytes hlc =');
  });

  it('offsets field numbers when type discriminator is present', () => {
    const proto = compileProto(`
speck OffsetTest {
  event Create {
    name: String
  }
  event Delete {
    id: Nat
  }
  oneof TransitionPayload {
    create: Create,
    delete: Delete
  }
  interface TransitionType {
    Create,
    Delete
  }
  transition Transition {
    type: TransitionType,
    payload: TransitionPayload,
    branch_id: Nat,
    hlc: Bytes
  }
}
`);
    // type = 1 (discriminator), then alphabetical fields offset by 1:
    // branch_id = 2 (alphabetically first, 1+1), hlc = 3 (2+1)
    expect(proto).toContain('TransitionType type = 1;');
    expect(proto).toContain('uint64 branch_id = 2;');
    expect(proto).toContain('bytes hlc = 3;');
  });

  it('emits transition without type discriminator when absent', () => {
    const proto = compileProto(`
speck NoDiscriminatorTest {
  event Create {
    name: String
  }
  oneof Payload {
    create: Create
  }
  transition Transition {
    payload: Payload,
    hlc: Bytes
  }
}
`);
    expect(proto).toContain('message Transition {');
    // No type discriminator → hlc starts at field 1 (alphabetically)
    expect(proto).toContain('bytes hlc = 1;');
    // oneof still at 10+
    expect(proto).toContain('oneof payload {');
    expect(proto).toContain('Create create = 10;');
  });
});

describe('Protobuf backend: service blocks', () => {
  it('parses service { rpc X(...) returns (...); } syntax cleanly', () => {
    const ast = parseInline(`
speck ServiceTest {
  service MyService {
    rpc GetItem(GetItemRequest) returns (GetItemResponse);
    rpc ListItems(ListItemsRequest) returns (ListItemsResponse);
  }
}
`);
    const service = ast.specks[0].members.find(m => m.type === 'service') as any;
    expect(service).toBeDefined();
    expect(service.name).toBe('MyService');
    expect(service.rpcs).toHaveLength(2);
    expect(service.rpcs[0].name).toBe('GetItem');
    expect(service.rpcs[0].requestType).toBe('GetItemRequest');
    expect(service.rpcs[0].responseType).toBe('GetItemResponse');
    expect(service.rpcs[1].name).toBe('ListItems');
    expect(service.rpcs[1].requestType).toBe('ListItemsRequest');
    expect(service.rpcs[1].responseType).toBe('ListItemsResponse');
  });

  it('emits service block with rpc methods in proto output', () => {
    const proto = compileProto(`
speck ServiceProtoTest {
  service HostService {
    rpc GetGroup(GetGroupRequest) returns (GetGroupResponse);
    rpc SubmitTransition(SubmitTransitionRequest) returns (SubmitTransitionResponse);
  }
}
`);
    expect(proto).toContain('service HostService {');
    expect(proto).toContain('rpc GetGroup(GetGroupRequest) returns (GetGroupResponse);');
    expect(proto).toContain('rpc SubmitTransition(SubmitTransitionRequest) returns (SubmitTransitionResponse);');
  });

  it('parses streaming rpc methods', () => {
    const ast = parseInline(`
speck StreamTest {
  service StreamService {
    rpc Subscribe(SubscribeRequest) returns (stream TransitionEvent);
  }
}
`);
    const service = ast.specks[0].members.find(m => m.type === 'service') as any;
    expect(service).toBeDefined();
    expect(service.rpcs).toHaveLength(1);
    expect(service.rpcs[0].name).toBe('Subscribe');
    expect(service.rpcs[0].serverStreaming).toBe(true);
    expect(service.rpcs[0].responseType).toBe('TransitionEvent');
  });

  it('emits streaming rpc methods with stream keyword', () => {
    const proto = compileProto(`
speck StreamProtoTest {
  service StreamService {
    rpc Subscribe(SubscribeRequest) returns (stream TransitionEvent);
  }
}
`);
    expect(proto).toContain('rpc Subscribe(SubscribeRequest) returns (stream TransitionEvent);');
  });

  it('converts snake_case rpc names to PascalCase in proto output', () => {
    const proto = compileProto(`
speck PascalRpcTest {
  service MyService {
    rpc get_group(GetGroupRequest) returns (GetGroupResponse);
    rpc submit_transition(SubmitTransitionRequest) returns (SubmitTransitionResponse);
  }
}
`);
    expect(proto).toContain('rpc GetGroup(GetGroupRequest) returns (GetGroupResponse);');
    expect(proto).toContain('rpc SubmitTransition(SubmitTransitionRequest) returns (SubmitTransitionResponse);');
  });

  it('throws on unrecognized lines in service blocks', () => {
    expect(() => parseInline(`
speck ErrorTest {
  service BadService {
    rc_typo(RequestType) returns (ResponseType);
  }
}
`)).toThrow(/unrecognized line/);
  });
});

