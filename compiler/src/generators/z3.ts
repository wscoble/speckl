/**
 * Parse invariants from the raw .speckdl source content.
 * This function is called with the raw file content and the speck name
 * to find and parse invariant blocks that the main parser doesn't handle yet.
 */
export function parseInvariantsFromSource(source: string, speckName: string): InvariantNode[] {
  const invariants: InvariantNode[] = [];

  // Find the speck block for this name
  const speckRegex = new RegExp(`speck\\s+${escapeRegex(speckName)}\\s*\\{`);
  const speckMatch = source.match(speckRegex);
  if (!speckMatch) return invariants;

  // Extract the speck body
  const startIdx = speckMatch.index! + speckMatch[0].length;
  let braceCount = 1;
  let endIdx = startIdx;
  for (let i = startIdx; i < source.length; i++) {
    if (source[i] === '{') braceCount++;
    if (source[i] === '}') {
      braceCount--;
      if (braceCount === 0) {
        endIdx = i;
        break;
      }
    }
  }

  const body = source.substring(startIdx, endIdx);

  // Find invariant blocks using brace counting (handles nested { })
  const invPattern = /invariant\s+(\w+)\s*\{/g;
  let match;
  while ((match = invPattern.exec(body)) !== null) {
    const name = match[1];
    // Find matching close brace
    const blockStart = match.index + match[0].length;
    let braceDepth = 1;
    let blockEnd = blockStart;
    for (let i = blockStart; i < body.length; i++) {
      if (body[i] === '{') braceDepth++;
      if (body[i] === '}') {
        braceDepth--;
        if (braceDepth === 0) {
          blockEnd = i;
          break;
        }
      }
    }
    const content = body.substring(blockStart, blockEnd);

    const statements = parseInvariantBody(content);
    invariants.push({ type: 'invariant', name, statements });
  }

  return invariants;
}

function parseInvariantBody(content: string): InvariantStatement[] {
  const statements: InvariantStatement[] = [];
  const lines = content.split('\n');

  let i = 0;
  while (i < lines.length) {
    const rawLine = lines[i];
    const line = rawLine.trim();
    if (!line || line.startsWith('//')) { i++; continue; }

    // forall var in domain: (body on next line(s))
    // domain can be: [0..4], someVar.keys, someVar.values, etc.
    const forallHeaderMatch = line.match(/^forall\s+(\w+)\s+in\s+(\[?[\w.\-\d]+\]?):\s*$/);
    if (forallHeaderMatch) {
      const bodyLines: string[] = [];
      i++;
      while (i < lines.length) {
        const nextLine = lines[i];
        if (!nextLine.trim() || nextLine.trim().startsWith('//')) { i++; continue; }
        // Don't break on nested forall — collect it as part of the body.
        // Only break on non-indented lines that aren't forall/implies/etc.
        if (!/^\s+/.test(nextLine) && !/^forall\s+/.test(nextLine.trim())) break;
        bodyLines.push(nextLine.trim());
        i++;
      }
      if (bodyLines.length > 0) {
        statements.push({
          type: 'forall',
          var: forallHeaderMatch[1],
          domain: forallHeaderMatch[2],
          expr: bodyLines.join(' '),
        });
      }
      continue;
    }

    // forall var in domain: expr (single line)
    // domain can be: [0..4], accounts.values, log.indices, transfers.keys, etc.
    const forallMatch = line.match(/^forall\s+(\w+)\s+in\s+(\[?[\w.\d\-]+\]?):\s*(.+)$/);
    if (forallMatch) {
      statements.push({
        type: 'forall',
        var: forallMatch[1],
        domain: forallMatch[2],
        expr: forallMatch[3].trim(),
      });
      i++; continue;
    }

    // forall var1, var2 in domain1, domain2: expr (complex)
    // domains may include bracket notation and dots
    const complexForallMatch = line.match(/^forall\s+([\w,\s]+)\s+in\s+([\[\]\w\s.,\-]+):\s*(.+)$/);
    if (complexForallMatch) {
      const vars = complexForallMatch[1].split(',').map((s: string) => s.trim()).filter(Boolean);
      const domains = complexForallMatch[2].split(',').map((s: string) => s.trim()).filter(Boolean);
      if (vars.length > 1 || domains.length > 1) {
        statements.push({
          type: 'forall_complex',
          vars, domains,
          expr: complexForallMatch[3].trim(),
        });
        i++; continue;
      }
      statements.push({
        type: 'forall',
        var: vars[0], domain: domains[0],
        expr: complexForallMatch[3].trim(),
      });
      i++; continue;
    }

    statements.push({ type: 'require', expr: line });
    i++;
  }

  return statements;
}

/**
 * Parse next: transition relation from raw source
 */
export function parseNextFromSource(source: string, speckName: string): NextNode | null {
  const speckRegex = new RegExp(`speck\\s+${escapeRegex(speckName)}\\s*\\{`);
  const speckMatch = source.match(speckRegex);
  if (!speckMatch) return null;

  const startIdx = speckMatch.index! + speckMatch[0].length;
  let braceCount = 1;
  let endIdx = startIdx;
  for (let i = startIdx; i < source.length; i++) {
    if (source[i] === '{') braceCount++;
    if (source[i] === '}') {
      braceCount--;
      if (braceCount === 0) {
        endIdx = i;
        break;
      }
    }
  }

  const body = source.substring(startIdx, endIdx);

  // next: Action1 | Action2 | ... (can span multiple lines)
  const nextMatch = body.match(/next:\s*(.+)/s);
  if (!nextMatch) return null;

  // The captured group contains everything from 'next' to end of speck body
  // We need to extract just the action names before the next block starts
  const rest = nextMatch[1];
  // Stop at verify: block, or end of speck body
  const endMarker = rest.match(/\n\s*(?:verify:|speck\s)/);
  const nextContent = endMarker ? rest.substring(0, endMarker.index!) : rest;

  const actions = nextContent
    .replace(/\n/g, ' ')  // collapse newlines
    .split('|')
    .map(s => s.trim())
    .filter(Boolean);

  return { type: 'next', actions };
}

function parseNext(speck: SpeckNode): NextNode | null {
  // Parsed from source, not AST
  return null;
}

function escapeRegex(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}
